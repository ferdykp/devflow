<?php

use App\Http\Controllers\Auth\AuthController;
use App\Http\Controllers\DocumentTaskImportController;
use App\Http\Controllers\FocusController;
use App\Http\Controllers\GitHubAppController;
use App\Http\Controllers\GithubController;
use App\Http\Controllers\PrdController;
use App\Http\Controllers\ProjectController;
use App\Http\Controllers\ProjectExtrasController;
use App\Http\Controllers\ProjectInsightsController;
use App\Http\Controllers\ProjectResumeController;
use App\Http\Controllers\ScopeController;
use App\Http\Controllers\TaskChecklistController;
use App\Http\Controllers\TaskCommentController;
use App\Http\Controllers\TaskController;
use App\Http\Controllers\WorkspaceController;
use App\Http\Controllers\WorkspaceMemberController;
use App\Models\Activity;
use App\Models\Project;
use App\Models\Task;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Route;

Route::get('/', fn () => redirect()->route(Auth::check() ? 'dashboard' : 'login'));
Route::middleware('guest')->group(function () {
    Route::get('/login', [AuthController::class, 'showLogin'])->name('login');
    Route::post('/login', [AuthController::class, 'login'])->middleware('throttle:login');
    Route::get('/register', [AuthController::class, 'showRegister'])->name('register');
    Route::post('/register', [AuthController::class, 'register'])->middleware('throttle:register');
});
Route::middleware(['auth', 'cache-history'])->group(function () {
    Route::get('/dashboard', function () {
        $projects = Project::whereHas('workspace', fn ($q) => $q->accessibleTo(auth()->id()))->withCount(['tasks', 'activities'])->latest()->limit(6)->get();
        $openTasks = Task::whereHas('project.workspace', fn ($q) => $q->accessibleTo(auth()->id()))->whereNotIn('status', ['done'])->count();
        $activities = Activity::whereHas('project.workspace', fn ($q) => $q->accessibleTo(auth()->id()))->with('project')->orderByDesc('occurred_at')->limit(8)->get();

        return view('dashboard.index', compact('projects', 'openTasks', 'activities'));
    })->name('dashboard');
    Route::post('/logout', [AuthController::class, 'logout'])->name('logout');
    Route::get('/workspaces/create', [WorkspaceController::class, 'create'])->name('workspaces.create');
    Route::post('/workspaces', [WorkspaceController::class, 'store'])->name('workspaces.store');
    Route::get('/workspaces/{workspace}/members', [WorkspaceMemberController::class, 'show'])->name('workspaces.members.show');
    Route::post('/workspaces/{workspace}/invitations', [WorkspaceMemberController::class, 'store'])->middleware('throttle:20,1')->name('workspaces.invitations.store');
    Route::delete('/workspaces/{workspace}/invitations/{invitation}', [WorkspaceMemberController::class, 'revoke'])->name('workspaces.invitations.destroy');
    Route::delete('/workspaces/{workspace}/members/{user}', [WorkspaceMemberController::class, 'destroy'])->name('workspaces.members.destroy');
    Route::get('/invitations/{token}', [WorkspaceMemberController::class, 'invitation'])->name('invitations.show');
    Route::post('/invitations/{token}', [WorkspaceMemberController::class, 'accept'])->middleware('throttle:20,1')->name('invitations.accept');
    Route::get('/projects', [ProjectController::class, 'index'])->name('projects.index');
    Route::get('/projects/create', [ProjectController::class, 'create'])->name('projects.create');
    Route::post('/projects', [ProjectController::class, 'store'])->name('projects.store');
    Route::get('/projects/{project}/edit', [ProjectController::class, 'edit'])->name('projects.edit');
    Route::get('/projects/{project}', [ProjectController::class, 'show'])->name('projects.show');
    Route::get('/projects/{project}/resume', [ProjectResumeController::class, 'show'])->name('projects.resume');
    Route::put('/projects/{project}', [ProjectController::class, 'update'])->name('projects.update');
    Route::delete('/projects/{project}', [ProjectController::class, 'destroy'])->name('projects.destroy');
    Route::post('/projects/{project}/tasks', [TaskController::class, 'store'])->name('tasks.store');
    Route::get('/projects/{project}/tasks/{task}', [TaskController::class, 'show'])->name('tasks.show');
    Route::patch('/projects/{project}/tasks/{task}', [TaskController::class, 'update'])->name('tasks.update');
    Route::patch('/projects/{project}/tasks/{task}/checklist/{item}', [TaskChecklistController::class, 'update'])->whereNumber('item')->name('task-checklist.update');
    Route::delete('/projects/{project}/tasks/{task}', [TaskController::class, 'destroy'])->name('tasks.destroy');
    Route::post('/projects/{project}/tasks/{task}/comments', [TaskCommentController::class, 'store'])->middleware('throttle:30,1')->name('task-comments.store');
    Route::delete('/projects/{project}/tasks/{task}/comments/{comment}', [TaskCommentController::class, 'destroy'])->name('task-comments.destroy');
    Route::get('/projects/{project}/task-imports/create', [DocumentTaskImportController::class, 'create'])->name('task-imports.create');
    Route::post('/projects/{project}/task-imports', [DocumentTaskImportController::class, 'store'])->middleware('throttle:10,1')->name('task-imports.store');
    Route::get('/projects/{project}/task-imports/{import}', [DocumentTaskImportController::class, 'show'])->name('task-imports.show');
    Route::patch('/projects/{project}/task-imports/{import}', [DocumentTaskImportController::class, 'update'])->name('task-imports.update');
    Route::post('/projects/{project}/notes', [ProjectExtrasController::class, 'note'])->name('notes.store');
    Route::post('/projects/{project}/milestones', [ProjectExtrasController::class, 'milestone'])->name('milestones.store');
    Route::post('/projects/{project}/backlog', [ProjectExtrasController::class, 'backlog'])->name('backlog.store');
    Route::get('/projects/{project}/insights', [ProjectInsightsController::class, 'show'])->name('projects.insights');
    Route::post('/projects/{project}/insights', [ProjectInsightsController::class, 'analyze'])->middleware('throttle:5,1')->name('projects.insights.analyze');
    Route::post('/projects/{project}/scope-baseline', [ProjectExtrasController::class, 'baseline'])->name('scope.baseline');
    Route::post('/projects/{project}/scope-reviews', [ScopeController::class, 'review'])->name('scope.review');
    Route::post('/projects/{project}/scope-reviews/{review}/decision', [ScopeController::class, 'decide'])->name('scope.decide');
    Route::post('/projects/{project}/scope-reviews/{review}/backlog', [ScopeController::class, 'backlog'])->name('scope.backlog');
    Route::post('/projects/{project}/documents', [PrdController::class, 'store'])->name('prd.store');
    Route::post('/projects/{project}/documents/{document}/versions', [PrdController::class, 'revise'])->name('prd.revise');
    Route::post('/projects/{project}/documents/{document}/versions/{version}/approve', [PrdController::class, 'approve'])->name('prd.approve');
    Route::get('/projects/{project}/github/authorize', [GitHubAppController::class, 'authorizeApp'])->name('github.app.authorize');
    Route::get('/github/callback', [GitHubAppController::class, 'callback'])->name('github.app.callback');
    Route::post('/projects/{project}/github/connect', [GitHubAppController::class, 'connect'])->name('github.app.connect');
    Route::post('/projects/{project}/repositories', [GithubController::class, 'link'])->name('github.link');
    Route::post('/projects/{project}/repositories/{repository}/sync', [GithubController::class, 'sync'])->middleware('throttle:8,1')->name('github.sync');
    Route::delete('/projects/{project}/repositories/{repository}', [GithubController::class, 'disconnect'])->name('github.disconnect');
    Route::get('/focus', [FocusController::class, 'index'])->name('focus.index');
    Route::post('/focus/{task}', [FocusController::class, 'toggle'])->name('focus.toggle');
});
